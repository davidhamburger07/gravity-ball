// build-levels.mjs — compile the hand-authored level folders into src/data/levels.json.
//
// Levels are authored as one JSON file per level under "GB - Levels/C<n> - <Name>/<n>-<m>.json".
// This script is the only thing that writes src/data/levels.json, which makes two guarantees:
//
//   1. THE FILENAME IS THE ID. Level ids are derived from the filename, never from the `id` field
//      inside the file. The editor defaults an id-less level to "custom-1" and that default has
//      round-tripped onto disk before, giving two different levels the same id — which would
//      silently break the unlock chain, the save keys and the HUD readout.
//   2. THE CHAPTER LIST LIVES HERE, not in the filesystem. Git cannot track an empty directory, so
//      a "coming soon" chapter with no levels yet would disappear on a fresh clone if the chapter
//      list were inferred from the folders.
//
// Usage:  node scripts/build-levels.mjs   (or `npm run levels:build`)
import { readdir, readFile, writeFile, copyFile, access } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC_DIR = resolve(ROOT, 'GB - Levels');
const OUT = resolve(ROOT, 'src/data/levels.json');

// The shipping campaign. `short` is the level-select tab label (keep it under ~10 characters);
